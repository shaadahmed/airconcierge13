export const paymentMoney = value => {
  const amount = Number(value)

  if (!Number.isFinite(amount))
    return '—'

  return amount.toLocaleString(undefined, { style: 'currency', currency: 'USD' })
}

export const paymentBookingLabel = payment => {
  if (!payment)
    return '—'

  const code = payment.booking_code || (payment.booking_id != null ? `#${payment.booking_id}` : null)
  const guest = payment.guest_name
  const start = payment.reservation_start_date
  const end = payment.reservation_end_date

  if (code && guest && start && end)
    return `${code} · ${guest} · ${start} – ${end}`

  if (code && guest)
    return `${code} · ${guest}`

  return code || '—'
}
